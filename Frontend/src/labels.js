export const label = (key) =>
  labels[key] || key.replace(/([a-z])([A-Z])/g, "$1 $2");
export const money = (value) =>
  new Intl.NumberFormat("vi-VN", {
    style: "currency",
    currency: "VND",
    maximumFractionDigits: 0,
  }).format(Number(value) || 0);
export function display(value, key = "") {
  if (value === null || value === undefined || value === "") return "—";
  if (typeof value === "boolean") return value ? "Có" : "Không";
  if (typeof value === "object")
    return (
      value.fullName ||
      value.name ||
      value.title ||
      value.className ||
      value.email ||
      (Array.isArray(value)
        ? value.length + " mục"
        : Object.keys(value).length + " trường")
    );
  if (enumLabels[value]) return enumLabels[value];
  if (
    /Amount$|^(amount|total|subtotal|discount|grandTotal|monthlyAmount)$/.test(
      key,
    )
  )
    return money(value);
  if (
    typeof value === "string" &&
    /^\d{4}-\d\d-\d\d/.test(value) &&
    !["startTime", "endTime"].includes(key)
  ) {
    const d = new Date(value);
    return isNaN(d) ? value : d.toLocaleDateString("vi-VN");
  }
  return String(value);
}
